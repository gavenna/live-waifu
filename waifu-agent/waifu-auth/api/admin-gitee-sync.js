// admin-gitee-sync — 从 Neon 重建 Gitee keys.txt
// 封禁/解绑后调用, 确保 keys.txt 与数据库中 active 用户一致

import { neon } from "@neondatabase/serverless";
import crypto from "crypto";

var DATABASE_URL = process.env.DATABASE_URL || "";
var sql = neon(DATABASE_URL);
var GITEE_PAT = process.env.GITEE_PAT || "";
var GITEE_REPO = process.env.GITEE_REPO || "gaven6666/waifu-agent-key";
var GITEE_API = "https://gitee.com/api/v5/repos/" + GITEE_REPO + "/contents/keys.txt";

async function handler(req, res) {
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type, Authorization");
  if (req.method === "OPTIONS") return res.status(204).end();
  if (req.method !== "POST") return res.status(405).json({ code: 1, message: "Method Not Allowed" });

  // Admin key check (reuse JWT + admin role)
  var jwt = await import("jsonwebtoken");
  var auth = (req.headers["authorization"] || "").match(/^Bearer\s+(.+)$/i);
  if (!auth) return res.status(401).json({ code: 1, message: "未提供 token" });
  var payload = jwt.default.verify(auth[1], process.env.JWT_SECRET || "dev-secret-change-in-production");
  if (payload.role !== "admin") return res.status(403).json({ code: 1, message: "仅限管理员" });

  if (!GITEE_PAT) return res.status(500).json({ code: 1, message: "GITEE_PAT 未配置" });

  try {
    // 查询所有 active (status=1) 用户的最新 access_token
    var users = await sql`
      SELECT u.id, u.display_id, u.tier, u.status,
             COALESCE(d.token_hash, '') as token_hash
      FROM users u
      LEFT JOIN LATERAL (
        SELECT token_hash FROM refresh_tokens WHERE user_id = u.id ORDER BY created_at DESC LIMIT 1
      ) d ON true
      WHERE u.status = 1
    `;

    // 构建 keys.txt 内容
    var lines = [
      "# waifu-agent licensed device tokens",
      "# auto-generated by admin-gitee-sync",
      "# synced at: " + new Date().toISOString(),
      "# total active users: " + users.length,
      "",
    ];
    for (var u of users) {
      if (u.token_hash) lines.push(u.token_hash + "  # " + u.display_id + " (" + u.tier + ")");
    }
    var content = lines.join("\n") + "\n";

    // 读取当前 Gitee 文件获取 SHA
    var sha = "";
    var getResp = await fetch(GITEE_API + "?access_token=" + GITEE_PAT);
    if (getResp.ok) {
      var data = await getResp.json();
      sha = data.sha;
    }

    var body = JSON.stringify({
      access_token: GITEE_PAT,
      content: Buffer.from(content).toString("base64"),
      message: "sync: " + users.length + " active users",
      sha: sha || void 0,
    });
    var putResp = await fetch(GITEE_API, { method: "PUT", headers: { "Content-Type": "application/json" }, body });
    if (!putResp.ok) {
      var err = await putResp.text();
      return res.status(500).json({ code: 1, message: "Gitee PUT failed: " + putResp.status, detail: err.slice(0, 500) });
    }
    return res.status(200).json({ code: 0, data: { users: users.length, message: "synced " + users.length + " users" } });
  } catch (e) {
    return res.status(500).json({ code: 99, message: "sync error: " + e.message });
  }
}

export { handler as default };
