#!/usr/bin/env bash
# report.sh — 合并各检查结果为 markdown 报告
# 用法: bash report.sh <results_dir> <output_file> <app_running> <timestamp>
set -e

RESULTS_DIR="${1:-.claude/skills/verify/results}"
OUTPUT="${2:-.claude/skills/verify/results/latest-report.md}"
APP_RUNNING="${3:-false}"
TIMESTAMP="${4:-$(date "+%Y-%m-%d %H:%M:%S")}"

# Convert Git Bash paths (/d/...) to Windows format (D:/...) for Python
to_winpath() { echo "$1" | sed 's|^/\([a-z]\)/|\1:/|' | sed 's|^/\([a-z]\)/|\1:/|'; }
RESULTS_DIR=$(to_winpath "$RESULTS_DIR")
OUTPUT=$(to_winpath "$OUTPUT")

# Use Python for all processing — avoids bash subshell/quoting issues
python -c "
import json, os, sys

results_dir = r'$RESULTS_DIR'
output = r'$OUTPUT'
app_running = '$APP_RUNNING'
timestamp = '$TIMESTAMP'

checks_map = {
  'check-settings.txt': 'Settings Integrity',
  'check-stickers.txt': 'Sticker Selection',
  'check-logs.txt': 'Log Analysis',
  'check-llm-output.txt': 'LLM Output Format',
  'check-content-quality.txt': 'Content Quality',
  'check-ui-commands.txt': 'UI Commands',
}

pass_total = 0; fail_total = 0; warn_total = 0; skip_total = 0
pass_items = []; fail_items = []; warn_items = []; skip_items = []
detail_sections = []

for fname, title in checks_map.items():
  fpath = os.path.join(results_dir, fname)
  if not os.path.exists(fpath):
    skip_total += 1
    skip_items.append(f'- **{title}**: not run')
    detail_sections.append(f'### {title} [SKIP]\nNot run.\n')
    continue

  with open(fpath, encoding='utf-8', errors='replace') as f:
    lines = f.readlines()

  # Find last valid JSON line
  data = None
  for line in reversed(lines):
    line = line.strip()
    if not line or not line.startswith('{'):
      continue
    try:
      data = json.loads(line)
      break
    except:
      continue

  if data is None:
    warn_total += 1
    warn_items.append(f'- **{title}**: could not parse output')
    continue

  status = data.get('status', 'warn')
  p = data.get('pass', 0)
  f = data.get('fail', 0)
  w = data.get('warn', 0)
  summary = data.get('summary', '')
  if isinstance(summary, dict):
    summary = ', '.join(f'{k}={v}' for k, v in summary.items())
  summary = str(summary)[:120]

  pass_total += p; fail_total += f; warn_total += w

  emoji = {'pass': '✅', 'fail': '❌', 'warn': '⚠️'}.get(status, '⚪')

  if status == 'fail':
    fail_items.append(f'- **{title}** — {summary}')
  elif status == 'warn':
    warn_items.append(f'- **{title}** — {summary}')
  else:
    pass_items.append(f'- **{title}** — {summary}')

  # Detail section
  checks = data.get('checks', [])
  section = f'### {emoji} {title}\n\n'
  for c in checks:
    ce = {'pass': '✅', 'fail': '❌', 'warn': '⚠️'}.get(c.get('status',''), '⚪')
    detail = c.get('detail', '')[:200]
    section += f'- {ce} **{c[\"name\"]}**\n'
    if detail:
      section += f'  {detail}\n'
  detail_sections.append(section)

# Overall
if fail_total > 0:
  overall = '❌ FAIL'
elif warn_total > 0:
  overall = '⚠️ WARN'
else:
  overall = '✅ PASS'

# Build report
report = f'''# waifu-agent Verification Report

**Time**: {timestamp}
**App Running**: {app_running}
**Overall**: {overall} ({pass_total} pass, {fail_total} fail, {warn_total} warn, {skip_total} skip)

---

## Results

'''
if fail_items:
  report += '### ❌ Failures\n' + '\n'.join(fail_items) + '\n\n'
if warn_items:
  report += '### ⚠️ Warnings\n' + '\n'.join(warn_items) + '\n\n'
if pass_items:
  report += '### ✅ Passed\n' + '\n'.join(pass_items) + '\n\n'
if skip_items:
  report += '### ⚪ Skipped\n' + '\n'.join(skip_items) + '\n\n'

report += '''---

## Details

'''
report += '\n'.join(detail_sections)

report += '''

---

## 👁 Needs Human Review

- Sticker image quality: check generated images in \`%APPDATA%/com.waifu-agent.app/stickers/\`
- TTS voice quality: verify edge-tts output sounds natural
- UI responsiveness: verify buttons react immediately
- Live2D animation: confirm mouth sync and expressions look natural

---

*Generated by /verify skill. Run \`/review\` for experience quality assessment.*
'''

with open(output, 'w', encoding='utf-8') as f:
  f.write(report)

# Avoid UnicodeEncodeError on Windows GBK terminals
try:
  print(overall)
except UnicodeEncodeError:
  print(overall.encode('ascii', errors='replace').decode('ascii'))
" 2>&1
